export async function listCommissionRules() {
  return db.commissionRule.findMany({
    include: { tenant: { select: { id: true, nameAr: true } } },
    orderBy: [{ tenantId: 'asc' }, { entityType: 'asc' }],
  });
}

export async function upsertCommissionRule(
  input: { id?: string; tenantId?: string | null; entityType: CommissionEntityType; percentage?: number | null; flatAmountMinor?: number | null; isActive?: boolean },
  actor: SessionUser
) {
  const data: Prisma.CommissionRuleUncheckedCreateInput = {
    tenantId: input.tenantId ?? null,
    entityType: input.entityType,
    percentage: input.percentage ?? null,
    flatAmountMinor: input.flatAmountMinor ?? null,
    isActive: input.isActive ?? true,
  };

  const rule = input.id
    ? await db.commissionRule.update({ where: { id: input.id }, data })
    : await db.commissionRule.create({ data });

  await recordAudit({
    actorUserId: actor.id,
    tenantId: rule.tenantId,
    action: input.id ? 'COMMISSION_RULE_UPDATED' : 'COMMISSION_RULE_CREATED',
    entityType: 'CommissionRule',
    entityId: rule.id,
    afterState: { entityType: rule.entityType, percentage: rule.percentage, flatAmountMinor: rule.flatAmountMinor },
  });

  return rule;
}

export async function listRepCommissions(representativeId: string) {
  const commissions = await db.commission.findMany({
    where: { representativeId },
    include: {
      appointment: {
        include: {
          doctor: { include: { user: { select: { name: true } } } },
          patient: { include: { user: { select: { name: true } } } },
        },
      },
    },
    orderBy: { createdAt: 'desc' },
  });

  const totals = commissions.reduce(
    (acc, c) => {
      if (c.status === 'PAID') acc.paidMinor += c.amountMinor;
      else if (c.status === 'PENDING') acc.pendingMinor += c.amountMinor;
      return acc;
    },
    { paidMinor: 0, pendingMinor: 0 }
  );

  return { commissions, ...totals };
}

export async function listTenantCommissions(tenantId: string) {
  return db.commission.findMany({
    where: { tenantId },
    include: { appointment: { select: { id: true, scheduledAt: true, priceMinor: true } } },
    orderBy: { createdAt: 'desc' },
    take: 200,
  });
}
